/// Resolve ordered system languages, matching regional and script variants.
/// Unsupported language lists fall back to English.
const appSupportedLocales = [Locale('en'), Locale('zh')];
Locale resolveAppLocale(List<Locale>? preferred, Iterable<Locale> supported) {
  for (final locale in preferred ?? const <Locale>[]) {
    if (locale.languageCode == 'zh') return const Locale('zh');
    if (locale.languageCode == 'en') return const Locale('en');
  }
  return const Locale('en');
}

/// Only UI templates are translated; argument values remain unchanged.
String appText(
  BuildContext context,
  String key, [
  List<Object?> arguments = const [],
]) {
  final messages = appMessages[key];
  assert(messages != null, 'Missing application message: $key');
  final language = Localizations.localeOf(context).languageCode;
  final template = messages == null ? key : messages[language == 'zh' ? 1 : 0];
  return template.replaceAllMapped(RegExp(r'\{(\d+)\}'), (match) {
    final index = int.parse(match[1]!);
    return index < arguments.length ? '${arguments[index]}' : match[0]!;
  });
}

